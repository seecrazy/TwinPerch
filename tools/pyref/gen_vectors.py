#!/usr/bin/env python3
"""生成 TP-Crypt v1 交叉验证测试向量。

输入全部由固定常量派生（sha256 of label），输出 vectors.json：
Swift 测试加载后，对握手派生物、每条 envelope 的字节、以及最终链状态做逐字节断言。
任何一侧实现变动导致分叉都会在此暴露。
"""

import hashlib
import json
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from tpcrypt_ref import (RefRatchet, handshake, seal_message, open_message,
                         _priv_pub, KIND_TEXT, KIND_ACK)


def fixed(label: str) -> bytes:
    return hashlib.sha256(("twinperch-vector/" + label).encode()).digest()


def main():
    ik_a = fixed("ik-a")
    ik_b = fixed("ik-b")
    ek_a = fixed("ek-a")
    ek_b = fixed("ek-b")
    sid = fixed("sid")[:16]
    nonce_a = fixed("nonce-a")[:16]
    nonce_b = fixed("nonce-b")[:16]
    step_ek_0 = fixed("step-ek-0")

    pub_a, pub_b = _priv_pub(ik_a), _priv_pub(ik_b)
    pub_ek_a, pub_ek_b = _priv_pub(ek_a), _priv_pub(ek_b)

    # 握手：双方各自推导，断言一致
    ha = handshake(True, ik_a, ek_a, pub_b, pub_ek_b, sid, nonce_a, nonce_b)
    hb = handshake(False, ik_b, ek_b, pub_a, pub_ek_a, sid, nonce_b, nonce_a)
    for k in ha:
        assert ha[k] == hb[k], f"handshake mismatch: {k}"

    # A 发 502 条（index 500 处触发一次 step）
    ra = RefRatchet(True, ik_a, pub_b, ha["k_confirm"], ha["root"], ha["seed_a"], ha["seed_b"],
                    step_eks=[step_ek_0])
    rb = RefRatchet(False, ik_b, pub_a, hb["k_confirm"], hb["root"], hb["seed_b"], hb["seed_a"],
                    step_eks=[])
    a_messages = []
    for i in range(502):
        payload = {"b": f"vector message {i}", "t": KIND_TEXT, "ts": 1700000000000 + i}
        env = seal_message(ra, sid, KIND_TEXT, payload)
        # Python 侧同步解密验证 + 推进 B 状态
        decoded = open_message(rb, sid, env)
        assert decoded["b"] == f"vector message {i}"
        a_messages.append({
            "i": i,
            "plaintext": payload["b"],
            "envelope": env.hex(),
            "dh_step": 1 if i >= 500 else 0,
        })

    # B 回 2 条文本 + 1 条 ACK 帧（B 的发送链独立，仍为 step 0）
    b_messages = []
    for i in range(2):
        payload = {"b": f"vector reply {i}", "t": KIND_TEXT, "ts": 1700000100000 + i}
        env = seal_message(rb, sid, KIND_TEXT, payload)
        assert open_message(ra, sid, env)["b"] == f"vector reply {i}"
        b_messages.append({"i": i, "plaintext": payload["b"], "envelope": env.hex()})
    ack_env = seal_message(rb, sid, KIND_ACK, {"t": KIND_ACK, "ack": 501})
    assert open_message(ra, sid, ack_env)["ack"] == 501
    b_messages.append({"i": 2, "plaintext": "ack:501", "envelope": ack_env.hex()})

    vectors = {
        "version": 1,
        "note": "TP-Crypt v1 cross-validation vectors, generated by tools/pyref/gen_vectors.py",
        "inputs": {
            "ik_a": ik_a.hex(), "ik_b": ik_b.hex(),
            "ek_a": ek_a.hex(), "ek_b": ek_b.hex(),
            "sid": sid.hex(),
            "nonce_a": nonce_a.hex(), "nonce_b": nonce_b.hex(),
            "step_eks": [step_ek_0.hex()],
        },
        "handshake": {k: (v.hex() if isinstance(v, bytes) else v) for k, v in ha.items()},
        "a_messages": a_messages,
        "b_messages": b_messages,
        "final_state": {
            "a_send_key": ra.send_key.hex(), "a_send_index": ra.send_index,
            "a_send_dh_step": ra.send_dh_step,
            "a_recv_index": ra.recv_index, "a_recv_dh_step": ra.recv_dh_step,
            "b_recv_key": rb.recv_key.hex(), "b_recv_index": rb.recv_index,
            "b_recv_dh_step": rb.recv_dh_step,
            "b_send_key": rb.send_key.hex(), "b_send_index": rb.send_index,
            "b_send_dh_step": rb.send_dh_step,
            "b_skipped_count": len(rb.skipped),
        },
    }

    out = os.path.join(os.path.dirname(__file__), "..", "..", "TwinPerch",
                       "Tests", "TwinPerchKitTests", "Fixtures", "vectors.json")
    with open(out, "w") as f:
        json.dump(vectors, f, indent=1)
    print(f"ok: {len(a_messages)} a_messages, {len(b_messages)} b_messages -> {out}")


if __name__ == "__main__":
    main()
